class ConfigError(Exception):
    pass


def load_toml(path):
    with open(path, "rb") as f:
        return tomllib.load(f)


def find(kind, name, company_dir=None):
    rel = KIND_FILE[kind].format(name)
    bases = ([company_dir / "custom" / kind] if company_dir else []) + [LIB / kind]
    for base in bases:
        if (base / rel).exists():
            return base / rel
    return None


def available(kind, company_dir=None):
    names = {}
    for base in [LIB / kind] + ([company_dir / "custom" / kind] if company_dir else []):
        if not base.exists():
            continue
        for p in sorted(base.iterdir()):
            name = p.stem if kind != "skills" else p.name
            if find(kind, name, company_dir):
                names[name] = "custom" if "custom" in p.parts else "library"
    return names


def frontmatter_field(text, field):
    m = re.search(rf"^{field}:\s*(.+)$", text.split("\n---", 1)[0], re.M)
    return m.group(1).strip().strip('"') if m else ""


