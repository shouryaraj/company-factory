def bullets(items, empty="- (none)"):
    return "\n".join(f"- {x}" for x in items) or empty


def context(cfg):
    co, tb = cfg["company"], cfg["taskboard"]
    founder, orch = co["founder_title"], cfg["orchestrator"]["title"]
    if tb["enabled"]:
        board_read = f"List open tickets in Taskboard project `{tb['project']}` (prefix `{tb['prefix']}`)."
        board_write = (f"Create each ticket in Taskboard project `{tb['project']}` with the owning role's agent "
                       f"(IDs in `company/board-ids.md`; run /setup-board if missing), priority, and definition of done in the description.")
        board_rule = (f"Track work on Taskboard project `{tb['project']}` (ticket keys `{tb['prefix']}-<n>`). "
                      "Subagents never call Taskboard; you do.")
    else:
        board_read = "Read `company/board.md`."
        board_write = f"Add each ticket to `company/board.md` as `{tb['prefix']}-<n> | <lane> | <role> | <title> | <done when>`."
        board_rule = f"Track work in `company/board.md` (ticket keys `{tb['prefix']}-<n>`). Only you edit it."
    roles_table = "\n".join(f"| `{r['id']}` | {r['title']} | {r['description']} |" for r in cfg["roles"])
    return {
        "company": co["name"], "founder": founder, "orchestrator": orch,
        "prefix": tb["prefix"], "project": tb["project"], "lanes": ", ".join(tb["lanes"]),
        "board_read": board_read, "board_write": board_write, "board_rule": board_rule,
        "roles_table": "| Agent | Title | Delegate when |\n|---|---|---|\n" + roles_table,
        "roles_list": "\n".join(f"- `{r['id']}`: {r['title']} (model {r['model']})" for r in cfg["roles"]),
        "factory": CMD,
    }


def sub(text, ctx):
    return Template(text).safe_substitute(ctx)


def render_claude_md(cfg, ctx):
    co = cfg["company"]
    owns = sorted({p for r in cfg["roles"] for p in r["owns"]})
    layout = "\n".join(
        f"| `{p}` | {', '.join(r['id'] for r in cfg['roles'] if p in r['owns'])} |" for p in owns)
    cmds = " · ".join(f"/{w}" for w in cfg["workflows"]["use"])
    return f"""{GEN_NOTE}
# {co['name']}: one human, many agents

This workspace *is* the company. The **{ctx['founder']}** (the only human) sets direction and approves anything external or irreversible. AI agents in `.claude/agents/` do the work.

## Your role in the main session: {ctx['orchestrator']}
1. Turn the {ctx['founder']}'s intent into tickets. {ctx['board_rule']}
2. Delegate each ticket to the role agent that owns it (table below). Run independent tickets in parallel; subagents cannot spawn subagents, so all routing goes through you.
3. Check each returned handoff (`handoffs/`) against the ticket's definition of done; send it back if it falls short.
4. Keep `company/decisions.md` and `company/approvals.md` current.
5. Do work yourself only when it is trivial. Escalate to the {ctx['founder']} only through `company/approvals.md` or when genuinely blocked.

## Binding context
- `company/operating-rules.md`: approval gates and autonomy. Applies to you and every agent.
- `company/charter.md` · `company/goals.md` · `company/org-chart.md`

## Team
{ctx['roles_table']}

## Layout
| Path | Owner |
|---|---|
| `company/` | {ctx['orchestrator']} + {ctx['founder']} |
| `handoffs/` | every agent (one file per finished ticket) |
{layout}

## Commands
{cmds}

## Marketplace skills
Some roles use skills from Claude Code plugin marketplaces (listed per agent as `plugin:skill`). If one is missing, install the company's plugins once: `{ctx['factory']} plugins . --install`.

## Changing the company
The company is defined by `company.toml` (+ `custom/` overrides). Edit it and rebuild: `{ctx['factory']} build .` Never hand-edit generated files (they carry the generated header); they are overwritten on rebuild.
"""


def render_rules(cfg, ctx):
    gates = "\n".join(f"| {g['name']} | {g['examples']} |" for g in cfg["gates"])
    rules = "\n".join(f"{i}. {sub(r, ctx)}" for i, r in enumerate(cfg["policy"]["rules"], 1))
    return f"""{GEN_NOTE}
# Operating rules (binding for every agent)

## 1. Approval gates: only the {ctx['founder']} decides
Agents may **prepare** these but never **do** them. Add a request under *Pending* in `company/approvals.md` and stop. When unsure whether something crosses a gate, treat it as a gate.

| Gate | Examples |
|---|---|
{gates}

## 2. Allowed without asking
{bullets(cfg['policy']['autonomy'])}

## 3. Working rules
{rules}

## 4. Handoff
End every ticket by writing `handoffs/{ctx['prefix']}-<n>-<role>.md` from `handoffs/TEMPLATE.md`, then return a summary of at most 10 lines to the {ctx['orchestrator']}.
"""


def render_charter(cfg, ctx):
    co = cfg["company"]
    sections = [f"{GEN_NOTE}\n# Charter: {co['name']}\n", f"## Mission\n{co['mission']}\n"]
    if co["bet"]:
        sections.append(f"## Current bet\n{co['bet'].strip()}\n")
    if co["icp"]:
        sections.append(f"## Customer (ICP)\n{co['icp'].strip()}\n")
    if co["principles"]:
        sections.append("## Principles\n" + "\n".join(f"{i}. {p}" for i, p in enumerate(co["principles"], 1)) + "\n")
    sections.append(f"## People\n- **{ctx['founder']}** (human): direction, money, anything external.\n"
                    f"- **{ctx['orchestrator']}** (main session): planning, delegation, review.\n"
                    f"- {len(cfg['roles'])} role agents: see `company/org-chart.md`.\n")
    return "\n".join(sections)


def render_org_chart(cfg, ctx):
    rows = "\n".join(
        f"| `{r['id']}` | {r['title']} | {r['model']} | {', '.join(f'`{p}`' for p in r['owns']) or '-'} | "
        f"{', '.join(r['skills']) or '-'} |" for r in cfg["roles"])
    return f"""{GEN_NOTE}
# Org chart

```
{ctx['founder']} (human)
  └─ {ctx['orchestrator']} (main session)
{chr(10).join(f"       ├─ {r['id']}" for r in cfg['roles'])}
```

| Agent | Title | Model | Owns | Skills |
|---|---|---|---|---|
{rows}

## When to delegate to whom
{ctx['roles_table']}
"""


def render_agent(role, cfg, ctx):
    skills = []
    for s in role["skills"]:
        desc = frontmatter_field(find("skills", s, cfg["_dir"]).read_text(encoding="utf-8"), "description")
        skills.append(f"`{s}` (`.claude/skills/{s}/SKILL.md`): {desc}")
    skills += [f"`{s}` (marketplace plugin; use it with the Skill tool when the work calls for it)" for s in role["plugin_skills"]]
    tools = f"tools: {', '.join(role['tools'])}\n" if role["tools"] else ""
    tools += f"skills: {', '.join(role['skills'])}\n" if role["skills"] else ""  # preloaded into the subagent
    desc = role["description"].replace("\n", " ")
    return f"""---
name: {role['id']}
description: {desc}
{tools}model: {role['model']}
---
{GEN_NOTE}
# {role['title']} at {ctx['company']}

You are the {role['title']} of {ctx['company']}. {role['mission']}

First, read `company/operating-rules.md` (binding) and `company/charter.md`. Then read the files named in your ticket.

## Responsibilities
{bullets([sub(x, ctx) for x in role['responsibilities']])}

## You own (edit only these paths, plus your handoff file)
{bullets([f'`{p}`' for p in role['owns']])}

## Skills: use the matching one before you start
{bullets(skills)}

## Never
{bullets([sub(x, ctx) for x in role['never']] + [f"Cross an approval gate. Add a request to `company/approvals.md` and stop."])}

## Definition of done
{bullets([sub(x, ctx) for x in role['done']] + [f"Handoff written to `handoffs/{ctx['prefix']}-<n>-{role['id']}.md`."])}

## Reporting
You report to the {ctx['orchestrator']}, not to the {ctx['founder']} directly. Return at most 10 lines: outcome, files changed, verification, open questions, approvals needed.
"""


def render_goals(cfg):
    out = ["# Goals", "", "Owned by the founder. Edit freely; the factory never overwrites this file.", ""]
    for g in cfg.get("goals", []):
        out += [f"## {g['objective']}", bullets(g.get("key_results", [])), ""]
    if not cfg.get("goals"):
        out += ["## <objective>", "- <key result, measurable, dated>", ""]
    return "\n".join(out)


