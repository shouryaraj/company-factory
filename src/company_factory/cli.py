def load_company(company_dir):
    path = company_dir / "company.toml"
    if not path.exists():
        raise ConfigError(f"{path} not found; run `{CMD} init {company_dir}` first")
    cfg = load_toml(path)
    defaults = load_toml(LIB / "defaults.toml")
    errors = []

    co = cfg.setdefault("company", {})
    for key in ("name", "mission"):
        if not co.get(key):
            errors.append(f"[company] needs `{key}`")
    co.setdefault("slug", re.sub(r"[^a-z0-9]+", "-", co.get("name", "company").lower()).strip("-"))
    co.setdefault("founder_title", "Founder")
    for key in ("bet", "icp"):
        co.setdefault(key, "")
    co.setdefault("principles", [])
    cfg.setdefault("orchestrator", {}).setdefault("title", "Chief of Staff")

    tb = cfg.setdefault("taskboard", {})
    tb.setdefault("enabled", False)
    tb.setdefault("project", f"{co.get('name', 'Company')} HQ")
    tb.setdefault("prefix", "TASK")
    tb.setdefault("lanes", defaults["lanes"])
    tb.setdefault("command", "taskboard")  # the Taskboard binary; `build` registers `<command> mcp` in .mcp.json
    tb.setdefault("mcp", True)
    if not re.fullmatch(r"[A-Z][A-Z0-9]{1,7}", tb["prefix"]):
        errors.append(f"[taskboard] prefix `{tb['prefix']}` must be 2-8 uppercase letters/digits")

    policy = cfg.setdefault("policy", {})
    # Each list either replaces the default (`rules = [...]`) or extends it (`extra_rules = [...]`).
    for key in ("autonomy", "rules"):
        policy[key] = policy.get(key, defaults[key]) + policy.get(f"extra_{key}", [])
    cfg["gates"] = cfg.get("gates", defaults["gates"]) + policy.get("extra_gates", [])

    role_defaults = cfg.get("defaults", {})
    roles, seen = [], set()
    for i, raw in enumerate(cfg.get("roles", [])):
        base = {}
        if "use" in raw:
            src = find("roles", raw["use"], company_dir)
            if not src:
                errors.append(f"role #{i + 1}: no role template `{raw['use']}` (see `{CMD} list roles`)")
                continue
            base = load_toml(src)
        role = {
            "model": role_defaults.get("model", "inherit"),
            "tools": role_defaults.get("tools", []),
            "skills": [], "plugin_skills": [], "owns": [], "responsibilities": [], "never": [], "done": [],
            **base,
            **{k: v for k, v in raw.items() if k != "use" and not k.endswith("_add")},
        }
        for key in ("skills", "plugin_skills", "owns", "responsibilities", "never", "done", "tools"):
            role[key] = list(role[key]) + [x for x in raw.get(f"{key}_add", []) if x not in role[key]]
        role["id"] = raw.get("id") or raw.get("use")
        rid = role["id"]
        if not rid or not re.fullmatch(r"[a-z][a-z0-9-]*", rid):
            errors.append(f"role #{i + 1}: `id` must be kebab-case (got {rid!r})")
            continue
        if rid in seen:
            errors.append(f"role `{rid}` defined twice")
        seen.add(rid)
        for key in ("title", "description", "mission"):
            if not role.get(key):
                errors.append(f"role `{rid}` needs `{key}`")
        if role["model"] not in MODELS:
            errors.append(f"role `{rid}`: model `{role['model']}` not in {sorted(MODELS)}")
        for skill in role["skills"]:
            if not find("skills", skill, company_dir):
                errors.append(f"role `{rid}`: unknown skill `{skill}` (see `{CMD} list skills`)")
        roles.append(role)
    if not roles:
        errors.append("define at least one [[roles]] entry")
    cfg["roles"] = roles
    load_plugins(cfg, defaults, errors)

    wf = cfg.setdefault("workflows", {}).setdefault("use", defaults["workflows"])
    for name in wf:
        if not find("workflows", name, company_dir):
            errors.append(f"[workflows] unknown workflow `{name}` (see `{CMD} list workflows`)")
    if not tb["enabled"] and "setup-board" in wf:
        wf.remove("setup-board")

    load_office(cfg, errors)
    if errors:
        raise ConfigError("\n".join(f"  - {e}" for e in errors))
    return cfg


def marketplace_source(spec):
    """"github:owner/repo" | "git:<url>" | "https://...git" | "path:<dir>" -> Claude Code marketplace source."""
    kind, _, rest = spec.partition(":")
    if kind == "github" and re.fullmatch(r"[\w.-]+/[\w.-]+", rest):
        return {"source": "github", "repo": rest}
    if kind == "git" and rest:
        return {"source": "git", "url": rest}
    if kind == "https" and spec.endswith(".git"):
        return {"source": "git", "url": spec}
    if kind == "path" and rest:
        return {"source": "directory", "path": rest}
    return None


def load_plugins(cfg, defaults, errors):
    """[plugins]: marketplace skills shared by the company, referenced by roles as "plugin:skill"."""
    own, base = cfg.get("plugins", {}), defaults["plugins"]
    markets = base["marketplaces"] | own.get("marketplaces", {})
    enable = own.get("enable", base["enable"]) + own.get("extra_enable", [])
    sources = {}
    for name, spec in markets.items():
        sources[name] = marketplace_source(spec)
        if not sources[name]:
            errors.append(f"[plugins] marketplace `{name}`: `{spec}` must be github:owner/repo, git:<url> or path:<dir>")
    enabled = {}
    for item in enable:
        plugin, _, market = item.partition("@")
        if not plugin or market not in markets:
            errors.append(f"[plugins] enable `{item}` must be plugin@marketplace with a marketplace from [plugins] marketplaces")
        enabled[plugin] = market
    for r in cfg["roles"]:
        for ps in r["plugin_skills"]:
            plugin, _, skill = ps.partition(":")
            if plugin not in enabled or not skill:
                errors.append(f"role `{r['id']}`: plugin skill `{ps}` needs `plugin:skill` with `{plugin}` in [plugins] enable")
    cfg["plugins"] = {"marketplaces": sources, "enable": enable}


def default_look(seed):
    """A stable look per id, so a role keeps its face across rebuilds."""
    h = hashlib.sha256(seed.encode()).digest()
    look = {k: v[h[i] % len(v)] for i, (k, v) in enumerate(PALETTE.items())}
    look |= {k: v[h[5 + i] % len(v)] for i, (k, v) in enumerate(LOOK_CHOICES.items())}
    return look


def check_look(seed, owner, look, errors):
    out = default_look(seed) | (look or {})
    for key in PALETTE:
        if not HEX.fullmatch(out[key]):
            errors.append(f"{owner}: look.{key} `{out[key]}` must be a #rrggbb color")
    for key, choices in LOOK_CHOICES.items():
        if out[key] not in choices:
            errors.append(f"{owner}: look.{key} `{out[key]}` must be one of {choices}")
    if unknown := set(out) - set(PALETTE) - set(LOOK_CHOICES):
        errors.append(f"{owner}: unknown look keys {sorted(unknown)}")
    return out


def load_office(cfg, errors):
    """[office]: the live view. Rooms default to one per role department."""
    office = cfg.setdefault("office", {})
    office.setdefault("title", f"{cfg['company']['name']} HQ")
    office.setdefault("subtitle", cfg["company"]["mission"])
    office.setdefault("port", 4477)
    office.setdefault("theme", "auto")
    office.setdefault("refresh_seconds", 5)
    office.setdefault("events", ".office/events.jsonl")
    office.setdefault("taskboard_url", "http://127.0.0.1:3010")
    if office["theme"] not in ("auto", "day", "night"):
        errors.append(f"[office] theme `{office['theme']}` must be auto, day or night")
    office["founder_look"] = check_look("founder", "[office] founder_look", office.get("founder_look"), errors)
    office["orchestrator_look"] = check_look("orchestrator", "[office] orchestrator_look", office.get("orchestrator_look"), errors)

    role_ids = [r["id"] for r in cfg["roles"]]
    if "rooms" not in office:
        depts = {}
        for r in cfg["roles"]:
            depts.setdefault(r.get("department", "team"), []).append(r["id"])
        office["rooms"] = [{"id": d, "title": d.replace("-", " ").title(), "roles": ids} for d, ids in depts.items()]
    placed = {}
    for room in office["rooms"]:
        rid = room.get("id", "")
        if not re.fullmatch(r"[a-z][a-z0-9-]*", rid) or rid in ("founder", "hub"):
            errors.append(f"[[office.rooms]] id {rid!r} must be kebab-case and not `founder` or `hub`")
        room.setdefault("title", rid.replace("-", " ").title())
        room.setdefault("roles", [])
        if "floor" in room and not HEX.fullmatch(room["floor"]):
            errors.append(f"room `{rid}`: floor `{room['floor']}` must be a #rrggbb color")
        for role in room["roles"]:
            if role not in role_ids:
                errors.append(f"room `{rid}`: unknown role `{role}`")
            elif role in placed:
                errors.append(f"role `{role}` is in rooms `{placed[role]}` and `{rid}`; pick one")
            placed[role] = rid
    if unplaced := [r for r in role_ids if r not in placed]:
        office["rooms"].append({"id": "floor", "title": "Open floor", "roles": unplaced})
        placed |= {r: "floor" for r in unplaced}
    for r in cfg["roles"]:
        r["room"] = placed[r["id"]]
        r["look"] = check_look(r["id"], f"role `{r['id']}`", r.get("look"), errors)


