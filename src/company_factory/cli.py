OFFICE_EVENTS = ["SessionStart", "UserPromptSubmit", "PreToolUse", "PostToolUse", "PostToolUseFailure",
                 "SubagentStart", "SubagentStop", "Stop", "Notification", "SessionEnd"]
# Claude Code kills async hooks when a `claude -p` run exits, so end-of-turn events record synchronously (~50 ms once per turn).
OFFICE_SYNC = {"Stop", "SessionEnd"}


def project_settings(cfg):
    """.claude/settings.json: office hooks plus the company's plugin marketplaces."""
    settings = json.loads(office_settings())
    if cfg["plugins"]["enable"]:
        settings["extraKnownMarketplaces"] = {k: {"source": v} for k, v in cfg["plugins"]["marketplaces"].items()}
        settings["enabledPlugins"] = {p: True for p in cfg["plugins"]["enable"]}
    return json.dumps(settings, indent=2) + "\n"


def office_settings():
    """Project hooks that feed the office. Async where it matters, so they never block a tool call."""
    def hook(ev):
        h = {"type": "command", "command": 'python3 "${CLAUDE_PROJECT_DIR}/.claude/hooks/office_event.py"'}
        return h if ev in OFFICE_SYNC else h | {"async": True}
    return json.dumps({"hooks": {ev: [{"matcher": "*", "hooks": [hook(ev)]} if "Tool" in ev else {"hooks": [hook(ev)]}]
                                 for ev in OFFICE_EVENTS}}, indent=2) + "\n"


def plan(company_dir, cfg):
    cfg["_dir"] = company_dir
    ctx = context(cfg)
    gen = {
        "CLAUDE.md": render_claude_md(cfg, ctx),
        "company/operating-rules.md": render_rules(cfg, ctx),
        "company/charter.md": render_charter(cfg, ctx),
        "company/org-chart.md": render_org_chart(cfg, ctx),
        "handoffs/TEMPLATE.md": GEN_NOTE + "\n" + (LIB / "handoff-template.md").read_text(encoding="utf-8"),
    }
    for role in cfg["roles"]:
        gen[f".claude/agents/{role['id']}.md"] = render_agent(role, cfg, ctx)
    for name in cfg["workflows"]["use"]:
        gen[f".claude/commands/{name}.md"] = sub(find("workflows", name, company_dir).read_text(encoding="utf-8"), ctx)
    skill_dirs = {s: find("skills", s, company_dir).parent for r in cfg["roles"] for s in r["skills"]}
    for name, src in skill_dirs.items():
        for f in src.rglob("*"):
            if f.is_file():
                gen[f".claude/skills/{name}/{f.relative_to(src)}"] = f.read_text(encoding="utf-8")
    gen[".claude/hooks/office_event.py"] = (LIB / "office" / "office_event.py").read_text(encoding="utf-8")
    gen[".claude/settings.json"] = project_settings(cfg)
    if cfg["taskboard"]["enabled"] and cfg["taskboard"]["mcp"]:
        gen[".mcp.json"] = json.dumps({"mcpServers": {"taskboard": {
            "type": "stdio", "command": cfg["taskboard"]["command"], "args": ["mcp"]}}}, indent=2) + "\n"
    once = {k: v for k, v in ONCE_FILES.items() if k != "company/board.md" or not cfg["taskboard"]["enabled"]}
    once["company/goals.md"] = render_goals(cfg)
    dirs = sorted({p for r in cfg["roles"] for p in r["owns"] if p.endswith("/")} | {"handoffs/"})
    return gen, once, dirs


def build(company_dir, dry_run=False, force=False):
    cfg = load_company(company_dir)
    gen, once, dirs = plan(company_dir, cfg)
    manifest_path = company_dir / MANIFEST
    old = set(json.loads(manifest_path.read_text(encoding="utf-8"))) if manifest_path.exists() else set()
    log = {"write": [], "unchanged": [], "create": [], "skip-user-file": [], "remove-stale": [], "mkdir": []}

    for rel, content in gen.items():
        p = company_dir / rel
        if p.exists() and rel not in old and not force:
            log["skip-user-file"].append(rel)
            continue
        if p.exists() and p.read_text(encoding="utf-8") == content:
            log["unchanged"].append(rel)
            continue
        log["write"].append(rel)
        if not dry_run:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8")
    for rel, content in once.items():
        p = company_dir / rel
        if not p.exists():
            log["create"].append(rel)
            if not dry_run:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(content, encoding="utf-8")
    for rel in sorted(old - set(gen)):
        if (company_dir / rel).exists():
            log["remove-stale"].append(rel)
            if not dry_run:
                (company_dir / rel).unlink()
    for d in dirs:
        p = company_dir / d
        if not p.exists():
            log["mkdir"].append(d)
            if not dry_run:
                p.mkdir(parents=True)
                (p / ".gitkeep").touch()
    if not dry_run:
        manifest_path.write_text(json.dumps(sorted(set(gen) - set(log["skip-user-file"])), indent=1) + "\n", encoding="utf-8")

    print(f"{'[dry run] ' if dry_run else ''}{cfg['company']['name']}: {len(cfg['roles'])} roles, "
          f"{len({s for r in cfg['roles'] for s in r['skills']})} skills, {len(cfg['workflows']['use'])} workflows")
    for action, items in log.items():
        if items and action != "unchanged":
            print(f"  {action}: " + ", ".join(items))
    if log["skip-user-file"]:
        print("  (skipped files exist but were not generated by the factory; rerun with --force to overwrite)")
    if ".mcp.json" in log["skip-user-file"]:
        print(f"  taskboard: your own .mcp.json was kept; make sure it has a `taskboard` server ({cfg['taskboard']['command']} mcp).")
    if cfg["plugins"]["enable"] and not dry_run:
        print(f"  plugins: {len(cfg['plugins']['enable'])} marketplace plugins declared; install them once with "
              f"`{CMD} plugins {company_dir} --install`")
    if ".claude/settings.json" in log["skip-user-file"]:
        print("  office: your own .claude/settings.json was kept, so live events are off. Merge the hooks from\n"
              f"          `{CMD} office-hooks` into it to turn them on.")


def plugins(company_dir, install=False):
    """Claude Code does not auto-install plugins a project enables; this installs (or prints) them."""
    import subprocess
    cfg = load_company(company_dir)
    cmds = [["claude", "plugin", "marketplace", "add", src.get("repo") or src.get("url") or src.get("path"), "--scope", "project"]
            for src in cfg["plugins"]["marketplaces"].values()]
    cmds += [["claude", "plugin", "install", p, "--scope", "project"] for p in cfg["plugins"]["enable"]]
    for c in cmds:
        print("$ " + " ".join(c), flush=True)
        if install:
            done = subprocess.run(c, cwd=company_dir)
            if done.returncode:
                sys.exit(f"`{' '.join(c)}` failed; fix it and rerun")
    if not install:
        print(f"(run `{CMD} plugins {company_dir} --install` to do this, then /reload-plugins in Claude Code)")


def init(company_dir, example):
    src = EXAMPLES / example
    if not (src / "company.toml").exists():
        raise ConfigError(f"no example `{example}`; choose from: {', '.join(examples())}")
    company_dir.mkdir(parents=True, exist_ok=True)
    copied = []
    for f in src.rglob("*"):
        if not f.is_file():
            continue
        rel = f.relative_to(src)
        rel = Path(*rel.parts[1:]) if rel.parts[0] == "seed" else rel
        if "__pycache__" in rel.parts:
            continue
        dst = company_dir / rel
        if not dst.exists():
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, dst)
            copied.append(str(rel))
    print(f"init {company_dir} from `{example}`: " + (", ".join(copied) or "nothing new (all files exist)"))
    print(f"next: edit {company_dir / 'company.toml'}, then `{CMD} build {company_dir}`")


def examples():
    """name -> one-line description (the first `# name: description` comment of its company.toml)."""
    out = {}
    for d in sorted(EXAMPLES.iterdir()):
        if (d / "company.toml").exists():
            first = (d / "company.toml").read_text(encoding="utf-8").split("\n", 1)[0]
            out[d.name] = first.split(":", 1)[-1].strip() if first.startswith("#") else ""
    return out


def demo(example, port, open_browser):
    """A throwaway company from an example, built and served with the office's demo playback."""
    company_dir = Path(tempfile.mkdtemp(prefix=f"company-factory-{example}-"))
    with contextlib.redirect_stdout(io.StringIO()):
        init(company_dir, example)
        build(company_dir)
        cfg = load_company(company_dir)
    from . import office
    office.seed_demo(cfg, company_dir)
    print(f"demo company `{example}` built in {company_dir}")
    print(f"  make it yours: {CMD} init ./my-company --example {example}")
    office.serve(company_dir, load_company, port, open_browser, demo=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version", action="version", version=f"company-factory {__version__}")
    sp = ap.add_subparsers(dest="cmd", required=True)
    p = sp.add_parser("demo", help="try the live office with a sample company (nothing to set up)")
    p.add_argument("--example", default="saas"); p.add_argument("--port", type=int)
    p.add_argument("--no-open", action="store_true", help="don't open a browser")
    p = sp.add_parser("init"); p.add_argument("dir"); p.add_argument("--example", default="starter")
    p = sp.add_parser("validate"); p.add_argument("dir")
    p = sp.add_parser("build"); p.add_argument("dir"); p.add_argument("--dry-run", action="store_true")
    p.add_argument("--force", action="store_true", help="overwrite existing files the factory did not create")
    p = sp.add_parser("list"); p.add_argument("kind", choices=[*KIND_FILE, "examples"]); p.add_argument("--dir")
    p = sp.add_parser("plugins", help="install the marketplace plugins the company enables")
    p.add_argument("dir"); p.add_argument("--install", action="store_true")
    sp.add_parser("office-hooks", help="print the hooks block the office needs in .claude/settings.json")
    p = sp.add_parser("office", help="open the live pixel office for a company")
    p.add_argument("dir"); p.add_argument("--port", type=int); p.add_argument("--open", action="store_true")
    p.add_argument("--demo", action="store_true", help="play scripted activity on top of the live office")
    a = ap.parse_args()
    try:
        if a.cmd == "demo":
            demo(a.example, a.port, not a.no_open)
        elif a.cmd == "init":
            init(Path(a.dir).resolve(), a.example)
        elif a.cmd == "validate":
            cfg = load_company(Path(a.dir).resolve())
            print(f"ok: {cfg['company']['name']} ({len(cfg['roles'])} roles)")
        elif a.cmd == "build":
            build(Path(a.dir).resolve(), a.dry_run, a.force)
        elif a.cmd == "plugins":
            plugins(Path(a.dir).resolve(), a.install)
        elif a.cmd == "office-hooks":
            print(office_settings(), end="")
        elif a.cmd == "office":
            from . import office
            office.serve(Path(a.dir).resolve(), load_company, a.port, a.open or a.demo, demo=a.demo)
        elif a.kind == "examples":
            for name, desc in examples().items():
                print(f"{name:22} {desc}")
        else:
            cdir = Path(a.dir).resolve() if a.dir else None
            for name, origin in available(a.kind, cdir).items():
                path = find(a.kind, name, cdir)
                text = path.read_text(encoding="utf-8")
                desc = load_toml(path).get("description", "") if a.kind == "roles" else frontmatter_field(text, "description")
                print(f"{name:22} [{origin}] {desc[:100]}")
    except ConfigError as e:
        sys.exit(f"config error:\n{e}")


if __name__ == "__main__":
    main()
