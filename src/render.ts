// Markdown the factory generates from a Config. Pure functions: Config in, text out.
import { readFileSync } from "node:fs";
import { CMD } from "./paths.js";
import { find, frontmatterField, type Config, type Role } from "./config.js";

export const GEN_NOTE = "<!-- generated by company-factory from company.toml: edit the config or library, then rebuild -->";

export type Ctx = Record<string, string>;

const bullets = (items: string[], empty = "- (none)") => items.map((x) => `- ${x}`).join("\n") || empty;

/** `$name` / `${name}` substitution that leaves unknown names (like Claude Code's $ARGUMENTS) alone; `$$` is a literal `$`. */
export const sub = (text: string, ctx: Ctx) =>
  text.replace(/\$(?:(\$)|\{([_a-zA-Z]\w*)\}|([_a-zA-Z]\w*))/g, (m, dollar, braced, bare) =>
    dollar ? "$" : (ctx[braced ?? bare] ?? m));

export function context(cfg: Config): Ctx {
  const { company: co, taskboard: tb } = cfg;
  let boardRead, boardWrite, boardRule;
  if (tb.enabled) {
    boardRead = `List open tickets in Taskboard project \`${tb.project}\` (prefix \`${tb.prefix}\`).`;
    boardWrite = `Create each ticket in Taskboard project \`${tb.project}\` with the owning role's agent ` +
      "(IDs in `company/board-ids.md`; run /setup-board if missing), priority, and definition of done in the description.";
    boardRule = `Track work on Taskboard project \`${tb.project}\` (ticket keys \`${tb.prefix}-<n>\`). Subagents never call Taskboard; you do.`;
  } else {
    boardRead = "Read `company/board.md`.";
    boardWrite = `Add each ticket to \`company/board.md\` as \`${tb.prefix}-<n> | <lane> | <role> | <title> | <done when>\`.`;
    boardRule = `Track work in \`company/board.md\` (ticket keys \`${tb.prefix}-<n>\`). Only you edit it.`;
  }
  const rolesTable = cfg.roles.map((r) => `| \`${r.id}\` | ${r.title} | ${r.description} |`).join("\n");
  return {
    company: co.name, founder: co.founder_title, orchestrator: cfg.orchestrator.title,
    prefix: tb.prefix, project: tb.project, lanes: tb.lanes.join(", "),
    board_read: boardRead, board_write: boardWrite, board_rule: boardRule,
    roles_table: "| Agent | Title | Delegate when |\n|---|---|---|\n" + rolesTable,
    roles_list: cfg.roles.map((r) => `- \`${r.id}\`: ${r.title} (model ${r.model})`).join("\n"),
    factory: CMD,
  };
}

export function claudeMd(cfg: Config, ctx: Ctx): string {
  const owns = [...new Set(cfg.roles.flatMap((r) => r.owns))].sort();
  const layout = owns.map((p) => `| \`${p}\` | ${cfg.roles.filter((r) => r.owns.includes(p)).map((r) => r.id).join(", ")} |`).join("\n");
  const plugins = cfg.plugins.enable.length
    ? `\n## Marketplace skills\nSome roles use skills from Claude Code plugin marketplaces (listed per agent as \`plugin:skill\`). If one is missing, install the company's plugins once: \`${ctx.factory} plugins . --install\`.\n`
    : "";
  return `${GEN_NOTE}
# ${cfg.company.name}: one human, many agents

This workspace *is* the company. The **${ctx.founder}** (the only human) sets direction and approves anything external or irreversible. AI agents in \`.claude/agents/\` do the work.

## Your role in the main session: ${ctx.orchestrator}
1. Turn the ${ctx.founder}'s intent into tickets. ${ctx.board_rule}
2. Delegate each ticket to the role agent that owns it (table below). Run independent tickets in parallel; subagents cannot spawn subagents, so all routing goes through you.
3. Check each returned handoff (\`handoffs/\`) against the ticket's definition of done; send it back if it falls short.
4. Keep \`company/decisions.md\` and \`company/approvals.md\` current.
5. Do work yourself only when it is trivial. Escalate to the ${ctx.founder} only through \`company/approvals.md\` or when genuinely blocked.

## Binding context
- \`company/operating-rules.md\`: approval gates and autonomy. Applies to you and every agent.
- \`company/charter.md\` · \`company/goals.md\` · \`company/org-chart.md\`

## Team
${ctx.roles_table}

## Layout
| Path | Owner |
|---|---|
| \`company/\` | ${ctx.orchestrator} + ${ctx.founder} |
| \`handoffs/\` | every agent (one file per finished ticket) |
${layout}

## Commands
${cfg.workflows.use.map((w) => `/${w}`).join(" · ")}
${plugins}
## Changing the company
The company is defined by \`company.toml\` (+ \`custom/\` overrides). Edit it and rebuild: \`${ctx.factory} build .\` Never hand-edit generated files (they carry the generated header); they are overwritten on rebuild.
`;
}

export function operatingRules(cfg: Config, ctx: Ctx): string {
  const gates = cfg.gates.map((g) => `| ${g.name} | ${g.examples} |`).join("\n");
  const rules = cfg.policy.rules.map((r, i) => `${i + 1}. ${sub(r, ctx)}`).join("\n");
  return `${GEN_NOTE}
# Operating rules (binding for every agent)

## 1. Approval gates: only the ${ctx.founder} decides
Agents may **prepare** these but never **do** them. Add a request under *Pending* in \`company/approvals.md\` and stop. When unsure whether something crosses a gate, treat it as a gate.

| Gate | Examples |
|---|---|
${gates}

## 2. Allowed without asking
${bullets(cfg.policy.autonomy)}

## 3. Working rules
${rules}

## 4. Handoff
End every ticket by writing \`handoffs/${ctx.prefix}-<n>-<role>.md\` from \`handoffs/TEMPLATE.md\`, then return a summary of at most 10 lines to the ${ctx.orchestrator}.
`;
}

export function charter(cfg: Config, ctx: Ctx): string {
  const co = cfg.company;
  const sections = [`${GEN_NOTE}\n# Charter: ${co.name}\n`, `## Mission\n${co.mission}\n`];
  if (co.bet) sections.push(`## Current bet\n${co.bet.trim()}\n`);
  if (co.icp) sections.push(`## Customer (ICP)\n${co.icp.trim()}\n`);
  if (co.principles.length) sections.push("## Principles\n" + co.principles.map((p, i) => `${i + 1}. ${p}`).join("\n") + "\n");
  sections.push(`## People\n- **${ctx.founder}** (human): direction, money, anything external.\n` +
    `- **${ctx.orchestrator}** (main session): planning, delegation, review.\n` +
    `- ${cfg.roles.length} role agents: see \`company/org-chart.md\`.\n`);
  return sections.join("\n");
}

export function orgChart(cfg: Config, ctx: Ctx): string {
  const rows = cfg.roles.map((r) =>
    `| \`${r.id}\` | ${r.title} | ${r.model} | ${r.owns.map((p) => `\`${p}\``).join(", ") || "-"} | ${r.skills.join(", ") || "-"} |`).join("\n");
  return `${GEN_NOTE}
# Org chart

\`\`\`
${ctx.founder} (human)
  └─ ${ctx.orchestrator} (main session)
${cfg.roles.map((r) => `       ├─ ${r.id}`).join("\n")}
\`\`\`

| Agent | Title | Model | Owns | Skills |
|---|---|---|---|---|
${rows}

## When to delegate to whom
${ctx.roles_table}
`;
}

export function agent(role: Role, cfg: Config, ctx: Ctx): string {
  const skills = role.skills.map((s) => {
    const desc = frontmatterField(readFileSync(find("skills", s, cfg.dir)!, "utf8"), "description");
    return `\`${s}\` (\`.claude/skills/${s}/SKILL.md\`): ${desc}`;
  });
  skills.push(...role.plugin_skills.map((s) => `\`${s}\` (marketplace plugin; use it with the Skill tool when the work calls for it)`));
  let meta = role.tools.length ? `tools: ${role.tools.join(", ")}\n` : "";
  meta += role.skills.length ? `skills: ${role.skills.join(", ")}\n` : "";  // preloaded into the subagent
  return `---
name: ${role.id}
description: ${role.description.replace(/\n/g, " ")}
${meta}model: ${role.model}
---
${GEN_NOTE}
# ${role.title} at ${ctx.company}

You are the ${role.title} of ${ctx.company}. ${role.mission}

First, read \`company/operating-rules.md\` (binding) and \`company/charter.md\`. Then read the files named in your ticket.

## Responsibilities
${bullets(role.responsibilities.map((x) => sub(x, ctx)))}

## You own (edit only these paths, plus your handoff file)
${bullets(role.owns.map((p) => `\`${p}\``))}

## Skills: use the matching one before you start
${bullets(skills)}

## Never
${bullets([...role.never.map((x) => sub(x, ctx)), "Cross an approval gate. Add a request to `company/approvals.md` and stop."])}

## Definition of done
${bullets([...role.done.map((x) => sub(x, ctx)), `Handoff written to \`handoffs/${ctx.prefix}-<n>-${role.id}.md\`.`])}

## Reporting
You report to the ${ctx.orchestrator}, not to the ${ctx.founder} directly. Return at most 10 lines: outcome, files changed, verification, open questions, approvals needed.
`;
}

export function goals(cfg: Config): string {
  const out = ["# Goals", "", "Owned by the founder. Edit freely; the factory never overwrites this file.", ""];
  for (const g of cfg.goals) out.push(`## ${g.objective}`, bullets(g.key_results ?? []), "");
  if (!cfg.goals.length) out.push("## <objective>", "- <key result, measurable, dated>", "");
  return out.join("\n");
}
